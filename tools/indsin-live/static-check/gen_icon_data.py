#!/usr/bin/env python3
"""يولّد app/src/main/java/com/dlof/rinlang/IndsinIconData.kt من جداول المحرّك الأصلي نفسها
(rin_indsin_icons.h: رموز نصية، rin_indsin_iconpaths.h: مسارات SVG + أسماء بديلة) فيبقى أندرويد والمحرّك والمتصفح على جدول واحد.
الاستعمال من جذر المستودع:  python3 tools/indsin-live/static-check/gen_icon_data.py   (أضف --check للتحقق دون كتابة)"""
import os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
CPP = os.path.join(ROOT, 'app/src/main/cpp/indsin')
OUT = os.path.join(ROOT, 'app/src/main/java/com/dlof/rinlang/IndsinIconData.kt')
icons = open(os.path.join(CPP, 'rin_indsin_icons.h'), encoding='utf8').read()
paths = open(os.path.join(CPP, 'rin_indsin_iconpaths.h'), encoding='utf8').read()

def cdecode(lit):  # C++ string literal body -> python str (\uXXXX, \UXXXXXXXX, \xHH.. bytes as UTF-8, simple escapes)
    out = bytearray(); i = 0
    while i < len(lit):
        c = lit[i]
        if c == '\\':
            n = lit[i + 1]
            if n == 'u': out += chr(int(lit[i + 2:i + 6], 16)).encode('utf8'); i += 6
            elif n == 'U': out += chr(int(lit[i + 2:i + 10], 16)).encode('utf8'); i += 10
            elif n == 'x':
                j = i + 2
                while j < len(lit) and lit[j] in '0123456789abcdefABCDEF': j += 1
                out.append(int(lit[i + 2:j], 16)); i = j
            else: out += {'n': b'\n', 't': b'\t', '"': b'"', '\\': b'\\', "'": b"'"}.get(n, n.encode()); i += 2
        else: out += c.encode('utf8'); i += 1
    return out.decode('utf8')

glyphs = {}
for name, lit in re.findall(r'glyphs\["([^"]+)"\]\s*=\s*"((?:[^"\\]|\\.)*)"', icons): glyphs[name] = cdecode(lit)
vecs = {n: p for n, _c, p in re.findall(r'\{"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"\}', paths.split('kIconAliases')[0])}
aliases = dict(re.findall(r'\{"([^"]+)",\s*"([^"]+)"\}', paths.split('kIconAliases')[1]))

def k(s):  # Kotlin string literal (escape $ and non-ASCII control)
    return '"' + ''.join('\\$' if ch == '$' else '\\"' if ch == '"' else '\\\\' if ch == '\\' else ch if ch.isprintable() and ord(ch) < 0x2E80 or ch.isprintable() else '\\u%04X' % ord(ch) for ch in s) + '"'
def kmap(name, d):
    rows = ',\n'.join(f'        {k(a)} to {k(b)}' for a, b in sorted(d.items()))
    return f'    val {name}: Map<String, String> = mapOf(\n{rows}\n    )\n'
src = ('// GENERATED by tools/indsin-live/static-check/gen_icon_data.py from the native engine tables -- do not edit by hand.\n'
       '// glyphs = rin_indsin_icons.h (typographic symbol per icon name), paths = rin_indsin_iconpaths.h (24x24 SVG path, stroke 2), aliases = alias -> vector name.\n'
       'package com.dlof.rinlang\n\ninternal object IndsinIconData {\n' + kmap('glyphs', glyphs) + '\n' + kmap('paths', vecs) + '\n' + kmap('aliases', aliases) + '}\n')
if '--check' in sys.argv:
    cur = open(OUT, encoding='utf8').read() if os.path.exists(OUT) else ''
    ok = cur == src
    print('icon data', 'OK' if ok else 'STALE (run gen_icon_data.py)', f'glyphs={len(glyphs)} paths={len(vecs)} aliases={len(aliases)}')
    sys.exit(0 if ok else 1)
open(OUT, 'w', encoding='utf8').write(src)
print(f'wrote {OUT}: glyphs={len(glyphs)} paths={len(vecs)} aliases={len(aliases)}')

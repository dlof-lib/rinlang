#!/usr/bin/env python3
"""Embeds client/index.html into live_client.h (so the server is one self-contained binary).

Run after editing client/index.html:   python3 tools/indsin-live/gen_client_h.py
The generated header is committed, so building the server never requires Python.
Chunks are kept under 8 KB per string literal (MSVC's limit is ~16 KB)."""
import os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "client", "index.html"), "rb").read()
out = ["// GENERATED by gen_client_h.py from client/index.html — do not edit by hand.\n",
       "#pragma once\n#include <cstddef>\nnamespace indsin_live {\n",
       "static const char kClientHtml[] =\n"]
CH = 4000
i = 0
n = len(src)
while i < n:
    chunk = src[i:i + CH]
    # never split inside a UTF-8 sequence (keeps the output readable and MSVC-safe)
    while i + len(chunk) < n and (src[i + len(chunk)] & 0xC0) == 0x80:
        chunk = src[i:i + len(chunk) + 1]
    i += len(chunk)
    esc = []
    for b in chunk:
        c = chr(b)
        if c == "\\": esc.append("\\\\")
        elif c == '"': esc.append('\\"')
        elif c == "\n": esc.append("\\n\"\n\"")
        elif c == "\r": esc.append("\\r")
        elif c == "\t": esc.append("\\t")
        elif 32 <= b < 127: esc.append(c)
        else: esc.append("\\%03o" % b)
    out.append('"' + "".join(esc) + '"\n')
out.append(";\nstatic const size_t kClientHtmlSize = sizeof(kClientHtml) - 1;\n}\n")
open(os.path.join(here, "live_client.h"), "w", newline="\n").write("".join(out))
print("wrote live_client.h (%d bytes of HTML)" % n)

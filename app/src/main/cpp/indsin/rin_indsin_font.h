// One decoded UTF-8 code point of a run; `glyph` is null for anything outside printable ASCII.
struct Cp { uint32_t cp; };

inline std::vector<uint32_t> decodeUtf8(const std::string& s) {
    std::vector<uint32_t> out;
    for (size_t i = 0; i < s.size();) {
        unsigned char c = (unsigned char)s[i];
        uint32_t cp = c; size_t n = 1;
        if (c >= 0xF0 && i + 3 < s.size() + 0) { cp = c & 0x07; n = 4; }
        else if (c >= 0xE0) { cp = c & 0x0F; n = 3; }
        else if (c >= 0xC0) { cp = c & 0x1F; n = 2; }
        for (size_t k = 1; k < n && i + k < s.size(); k++) cp = (cp << 6) | ((unsigned char)s[i + k] & 0x3F);
        out.push_back(cp); i += n;
    }
    return out;
}

// True for code points in the right-to-left blocks (Hebrew, Arabic, Syriac, Thaana, NKo, presentation forms).
inline bool isRtlCp(uint32_t cp) {
    return (cp >= 0x0590 && cp <= 0x08FF) || (cp >= 0xFB1D && cp <= 0xFDFF) || (cp >= 0xFE70 && cp <= 0xFEFF);
}

// First strong direction wins (the same rule CSS `dir=auto` / Android's TextDirectionHeuristics.FIRSTSTRONG use).
inline bool isRtlText(const std::string& s) {
    for (uint32_t cp : decodeUtf8(s)) {
        if (isRtlCp(cp)) return true;
        if ((cp >= 'A' && cp <= 'Z') || (cp >= 'a' && cp <= 'z') || (cp >= 0xC0 && cp < 0x0590)) return false;
    }
    return false;
}

// Font metrics shared by the rasterizer and the wrapping code so both agree on the run width.
// A glyph cell is 6 units wide (5 columns + 1 gap) and the cap height is 7 units; the scale is chosen so
// the cap height is 0.72 * fontSize, which matches how a typical UI sans-serif (Roboto/Inter) sizes caps.
inline double unitFor(double fontSize) { return fontSize * 0.72 / 7.0; }
inline double advanceFor(double fontSize) { return 6.0 * unitFor(fontSize); }
inline double runWidth(size_t glyphCount, double fontSize) { return glyphCount * advanceFor(fontSize); }

